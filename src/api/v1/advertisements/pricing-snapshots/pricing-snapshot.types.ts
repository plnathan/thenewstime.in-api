export type AdvertisementPricingSnapshotPricingUnit =
  "DAY" | "WEEK" | "MONTH" | "IMPRESSION" | "CAMPAIGN" | "FIXED";

export interface AdvertisementPricingSnapshot {
  id: number;
  advertisementId: number;
  placementId: number;
  rateCardId: number;

  pricingUnit: AdvertisementPricingSnapshotPricingUnit;

  /*
   * Historical rate copied from the rate card at snapshot creation.
   *
   * This value must never change when the rate card is subsequently
   * updated.
   */
  rateAmount: number;

  currencyCode: string;

  rateEffectiveFrom: Date;
  rateEffectiveTo: Date | null;

  /*
   * Explicit billable quantity captured at the time of pricing.
   *
   * Optional for compatibility with existing repository/service
   * test fixtures created before snapshot quantity was persisted.
   *
   * Newly created database snapshots should contain this value.
   */
  quantity?: number | null;

  /*
   * System-calculated standard amount captured at the time of pricing.
   *
   * This is immutable historical pricing data and is independent from
   * the advertisement's negotiated/agreed commercial amount.
   *
   * Optional for compatibility with existing repository/service
   * test fixtures created before standardAmount was persisted in the
   * snapshot domain model.
   */
  standardAmount?: number | null;

  snapshotAt: Date;

  createdBy: number;
  createdAt: Date;
}

export interface CreateAdvertisementPricingSnapshotInput {
  advertisementId: number;
  placementId: number;
  rateCardId: number;

  pricingUnit: AdvertisementPricingSnapshotPricingUnit;

  rateAmount: number;
  currencyCode?: string | undefined;

  rateEffectiveFrom: string | Date;
  rateEffectiveTo?: string | Date | null | undefined;

  snapshotAt?: string | Date | undefined;

  /*
   * Quantity and standard amount are generated by the pricing service
   * from the advertisement pricing configuration and active rate card.
   */
  quantity?: number | null;
  standardAmount?: number | null;
}
